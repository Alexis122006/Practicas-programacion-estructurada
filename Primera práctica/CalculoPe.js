//Cálculo de Perímetro y Área de un Círculo
//Declare una variable que contenga el radio de un círculo
//Mensaje que indique qué valor es el perímetro y cuál es el área.


let radio = 2.5;   
let perimetro = 2 * 3.14159 * radio;
let area = 3.14159 * radio * radio;

console.log(`El perímetro del círculo es: ${perimetro.toFixed(2)}`);
console.log(`El área del círculo es: ${area.toFixed(2)}`); 

